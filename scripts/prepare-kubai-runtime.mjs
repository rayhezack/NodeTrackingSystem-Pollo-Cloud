import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../client/src/components/kubai/', import.meta.url);
const parts = ['artwork/src/engine.js', 'artwork/src/icons.js', 'runtime-adapter.js'];
const source = '// Generated by scripts/prepare-kubai-runtime.mjs; edit the adapter or artwork sources.\n'
  + parts.map((file) => readFileSync(new URL(file, root), 'utf8')).join('\n');
const target = new URL('runtime.generated.js', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('Kubai runtime is stale');
} else writeFileSync(target, source);
